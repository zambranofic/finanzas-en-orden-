import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {renewalReturnDestination} from './renewal-return-utils.js';
assert.equal(renewalReturnDestination('?returnTo=%2Frenovar.html'),'/renovar.html');
for(const value of ['','?returnTo=https://example.com','?returnTo=//example.com','?returnTo=/admin','?returnTo=/renovar.html%3Fevil=1'])assert.equal(renewalReturnDestination(value),null);
const app=fs.readFileSync(new URL('./app-v4.js',import.meta.url),'utf8');
const start=app.indexOf('async function enterApp()'),end=app.indexOf('\nfunction showAccessPending',start);
let destination=null,licenseCalls=0;
const ctx=vm.createContext({renewalReturnDestination,location:{search:'?returnTo=%2Frenovar.html',assign:v=>destination=v},cloud:{currentUser:async()=>({id:'expired-account'}),myLicense:async()=>{licenseCalls++;throw Error('Should return to renewal before license gate')}},showAuth:e=>{throw Error(e)}});
vm.runInContext(app.slice(start,end),ctx);
await vm.runInContext('enterApp()',ctx);
assert.equal(destination,'/renovar.html');assert.equal(licenseCalls,0);
const source=fs.readFileSync(new URL('./renew-membership.js',import.meta.url),'utf8');
const elements=new Map(['membership-summary','check-status','renew-form'].map(id=>[id,{append(...children){this.children=children}}]));
let infoCalls=0;
const renewctx=vm.createContext({document:{getElementById:id=>elements.get(id)||null,createElement:tag=>({tag})},window:{addEventListener:()=>{}},currentUser:async()=>null,membershipRequest:async()=>{infoCalls++},membershipGuestRequest:async()=>{infoCalls++},setTimeout:()=>{},clearTimeout:()=>{}});
vm.runInContext(source.replace(/^import .*;\n/,'' ).replace('void boot();','globalThis.done=boot();'),renewctx);await renewctx.done;
assert.equal(elements.get('membership-summary').children[1].href,'/?returnTo=%2Frenovar.html');assert.equal(infoCalls,0);
console.log('renewal-return-tests: sign-in link, expired-account return and redirect allowlist PASS');
